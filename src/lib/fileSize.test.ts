import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { countPhysicalLines, detectFileSizes, isCodePath, summarizeFileSizes } from './fileSize';

const lines = (count: number) => Array.from({ length: count }, (_, i) => `const v${i} = ${i};`).join('\n') + '\n';

function gitAvailable(): boolean {
  try {
    execFileSync('git', ['--version'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

describe('countPhysicalLines', () => {
  it('counts lines with and without a trailing newline', () => {
    expect(countPhysicalLines('')).toBe(0);
    expect(countPhysicalLines('a')).toBe(1);
    expect(countPhysicalLines('a\nb\n')).toBe(2);
    expect(countPhysicalLines('a\n\nb')).toBe(3);
  });
});

describe('isCodePath', () => {
  it('accepts code extensions and rejects prose, config, minified, and declaration files', () => {
    expect(isCodePath('src/lib/scanner.ts')).toBe(true);
    expect(isCodePath('src/routes/+page.svelte')).toBe(true);
    expect(isCodePath('app/models.py')).toBe(true);
    expect(isCodePath('README.md')).toBe(false);
    expect(isCodePath('package.json')).toBe(false);
    expect(isCodePath('Makefile')).toBe(false);
    expect(isCodePath('static/vendor.min.js')).toBe(false);
    expect(isCodePath('src/types.d.ts')).toBe(false);
    expect(isCodePath('src/api.generated.ts')).toBe(false);
  });
});

describe('summarizeFileSizes', () => {
  it('counts bands and lists the largest files with tests tagged', () => {
    const result = summarizeFileSizes([
      { path: 'src/small.ts', lines: 40 },
      { path: 'src/big.ts', lines: 1200 },
      { path: 'src/medium.ts', lines: 600 },
      { path: 'src/medium.test.ts', lines: 700 }
    ]);

    expect(result).toEqual({
      status: 'measured',
      codeFileCount: 4,
      codeLineCount: 2540,
      filesOver500Lines: 3,
      filesOver1000Lines: 1,
      largestFiles: [
        'src/big.ts (1200 lines)',
        'src/medium.test.ts (700 lines, test)',
        'src/medium.ts (600 lines)',
        'src/small.ts (40 lines)'
      ]
    });
  });

  it('keeps only the ten largest files', () => {
    const files = Array.from({ length: 12 }, (_, i) => ({ path: `src/f${i}.ts`, lines: i + 1 }));

    const result = summarizeFileSizes(files);

    expect(result.largestFiles).toHaveLength(10);
    expect(result.largestFiles?.[0]).toBe('src/f11.ts (12 lines)');
  });
});

describe('detectFileSizes', () => {
  let repoDir: string;

  beforeEach(async () => {
    repoDir = await mkdtemp(join(tmpdir(), 'repo-scorer-filesize-'));
  });

  afterEach(async () => {
    await rm(repoDir, { recursive: true, force: true });
  });

  it('walks a non-git directory and skips dependency, generated, and non-code files', async () => {
    await mkdir(join(repoDir, 'src'), { recursive: true });
    await mkdir(join(repoDir, 'node_modules/pkg'), { recursive: true });
    await writeFile(join(repoDir, 'src/big.ts'), lines(1001));
    await writeFile(join(repoDir, 'src/small.ts'), lines(10));
    await writeFile(join(repoDir, 'src/schema.ts'), '// @generated by a tool\n' + lines(2000));
    await writeFile(join(repoDir, 'src/api.ts'), '// Generated by a script. Do not edit manually.\n' + lines(2000));
    await writeFile(join(repoDir, 'node_modules/pkg/index.js'), lines(5000));
    await writeFile(join(repoDir, 'README.md'), lines(900));

    const result = await detectFileSizes(repoDir);

    expect(result).toMatchObject({
      status: 'measured',
      codeFileCount: 2,
      codeLineCount: 1011,
      filesOver500Lines: 1,
      filesOver1000Lines: 1,
      largestFiles: ['src/big.ts (1001 lines)', 'src/small.ts (10 lines)']
    });
  });

  it.runIf(gitAvailable())('honors .gitignore in a git repository', async () => {
    execFileSync('git', ['init', '-q'], { cwd: repoDir });
    await mkdir(join(repoDir, 'out'), { recursive: true });
    await writeFile(join(repoDir, '.gitignore'), 'out/\n');
    await writeFile(join(repoDir, 'out/bundle.js'), lines(3000));
    await writeFile(join(repoDir, 'main.go'), lines(20));

    const result = await detectFileSizes(repoDir);

    expect(result).toMatchObject({ status: 'measured', codeFileCount: 1, largestFiles: ['main.go (20 lines)'] });
  });
});
